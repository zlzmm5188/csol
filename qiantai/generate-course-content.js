// 生成通用课程内容的函数
function generateCourseContent(course) {
  const levelDesc = {
    '入门': '本课程适合投资新手，从零开始系统学习',
    '进阶': '本课程需要一定基础，帮助你进一步提升投资能力',
    '高级': '本课程面向有经验的投资者，深入探讨高级投资策略'
  };

  const categoryNames = {
    'fund': '基金投资',
    'ipo': 'IPO新股',
    'bond': '债券投资'
  };

  return {
    intro: `欢迎学习《${course.title}》！${levelDesc[course.level]}。通过本课程的学习，你将掌握关键的投资知识和实战技巧。`,
    objectives: [
      `深入理解${course.title}的核心概念和原理`,
      `掌握${categoryNames[course.category]}领域的实用技巧`,
      `学会运用所学知识进行实际投资决策`,
      `提升${course.level}阶段的专业投资能力`
    ],
    sections: [
      {
        title: "核心概念讲解",
        text: `在本章节中，我们将系统学习${course.title}的基本定义、发展历程和重要意义。理解这些基础概念是掌握后续知识的关键。`,
        tips: `建议先理解核心概念，再进入实战应用阶段。`
      },
      {
        title: "关键要点分析",
        text: `本节重点分析${course.title}中的关键要点和注意事项。我们将通过实际案例，帮助你深入理解这些要点在实战中的应用。`,
        tips: `重点关注案例分析，思考如何将理论应用到实际投资中。`
      },
      {
        title: "实战技巧分享",
        text: `在掌握了理论知识后，本节将分享实用的投资技巧和策略。这些技巧都是经过市场验证的，可以直接应用到你的投资实践中。`,
        tips: `建议边学边实践，通过模拟投资来验证所学技巧。`
      },
      {
        title: "风险管理要点",
        text: `任何投资都伴随风险，本节将详细讲解${categoryNames[course.category]}中的常见风险，以及相应的防范和应对策略。学会风险管理是长期成功的关键。`,
        tips: `风险管理永远是第一位的，不要为了追求高收益而忽视风险。`
      }
    ],
    summary: `通过本课程的系统学习，你已经掌握了${course.title}的核心知识和实战技巧。记住，投资是一个持续学习的过程，建议定期回顾本课程内容，并结合市场实践不断深化理解。`,
    nextSteps: [
      `复习本课程的关键知识点，确保完全理解`,
      `进入下一课程，继续深入学习`,
      `将所学知识应用到实际投资中，积累经验`,
      `关注市场动态，持续提升投资能力`
    ]
  };
}

